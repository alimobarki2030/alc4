#!/usr/bin/env node
// Builds js/data-words.js — every vocabulary word from every book, for the
// «كلمات كل الكتب» dictionary and the «تحدّى نفسك» challenge.
// Each book's data file declares the same global names (VOCAB, EE…), so they
// can't be loaded together in one page; this script merges their VOCAB.
//
//   node tools/build-words.js        (run from the repo root after editing any book's VOCAB)
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const books=fs.readdirSync(path.join(root,'js')).map(f=>(f.match(/^data-book(\d+)\.js$/)||[])[1]).filter(Boolean).map(Number).sort((a,b)=>a-b);
const out=[];
for(const b of books){
  global.dedupe_by_q=x=>x;
  let V,K,M;
  eval(fs.readFileSync(path.join(root,'js',`data-book${b}.js`),'utf8').replace(/^const /gm,'var ')+
       ';V=VOCAB;K=typeof LESSON_KEYS!=="undefined"?LESSON_KEYS:Object.keys(VOCAB);M=typeof LESSON_META!=="undefined"?LESSON_META:{};');
  K.forEach((k,li)=>(V[k]||[]).forEach(w=>{
    const r={e:w.e,a:w.a,b,l:li+1};
    if(w.alt&&w.alt.length)r.alt=w.alt;
    if(w.past)r.past=w.past;
    if(w.pa)r.pa=w.pa;
    out.push(r);
  }));
}
const js='// AUTO-GENERATED by tools/build-words.js — do not edit by hand.\n'+
  '// {e: English, a: Arabic, alt: accepted alternatives, past/pa: past form + meaning, b: book, l: lesson}\n'+
  'const ALL_WORDS='+JSON.stringify(out)+';\n';
fs.writeFileSync(path.join(root,'js','data-words.js'),js);
console.log(`books ${books.join(',')} · ${out.length} words · ${(js.length/1024).toFixed(0)} KB`);
